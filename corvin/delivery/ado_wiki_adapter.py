"""
ADO Wiki Adapter — creates a Wiki page per investigation in Azure DevOps.

Page structure:
  Investigations/
    2026-05-21_fundsso_production/
      (full RCA + fix strategy as markdown)

Uses the same PAT and org/project as the work-item adapter.
Config lives in config/integrations/azure_devops.yaml (reuses existing keys).
"""

from __future__ import annotations

import base64
import logging
import re
from datetime import datetime, timezone
from typing import Any, Optional

import httpx

from corvin.core.contracts import InvestigationResult

logger = logging.getLogger(__name__)

# Root path under which all investigation pages are created.
_WIKI_ROOT = "Investigations"


def _b64_auth(pat: str) -> str:
    return base64.b64encode(f":{pat}".encode("ascii")).decode("ascii")


def _safe_path_segment(value: str) -> str:
    """Turn arbitrary text into a safe Wiki path segment."""
    value = re.sub(r"[^\w\- ]", "", value)
    return value.strip().replace(" ", "_")[:60]


def _build_wiki_content(result: InvestigationResult) -> str:
    """Build a Markdown Wiki page from an InvestigationResult."""
    rca = result.rca
    fix = result.fix_strategy
    confidence_raw = rca.confidence.value if hasattr(rca.confidence, "value") else str(rca.confidence or "medium")
    confidence = (confidence_raw or "medium").upper()

    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    lines: list[str] = [
        f"# Corvin Investigation — {result.request.service_name} ({result.request.environment})",
        "",
        f"**Generated:** {ts}  ",
        f"**Investigation ID:** `{result.request_id}`  ",
        f"**Triggered by:** {result.request.trigger_source.value}  ",
        f"**Confidence:** {confidence}  ",
        "",
        "---",
        "",
        "## Root Cause Summary",
        "",
        rca.summary or "_No summary available._",
        "",
        "## Root Cause Detail",
        "",
        rca.root_cause or "_No root cause identified._",
        "",
    ]

    if fix and fix.actions:
        lines += [
            "## Proposed Fix Actions",
            "",
        ]
        for i, action in enumerate(fix.actions, 1):
            lines.append(f"### {i}. {action.title}")
            lines.append("")
            lines.append(action.description or "")
            lines.append("")
            if getattr(action, "risk_level", None):
                lines.append(f"**Risk:** {action.risk_level}")
                lines.append("")

    lines += [
        "---",
        "",
        "_Generated by Corvin AI SRE Co-Pilot_",
    ]

    return "\n".join(lines)


class ADOWikiAdapter:
    """
    Publishes investigation RCA pages to an Azure DevOps Wiki.

    Reuses the same PAT/org/project as AzureDevOpsAdapter.
    The wiki_id must be the wiki identifier — either the wiki slug or GUID
    from: GET https://dev.azure.com/{org}/{project}/_apis/wiki/wikis?api-version=7.1
    """

    def __init__(self, config: dict[str, Any]) -> None:
        self._enabled: bool = config.get("wiki_enabled", False)
        self._org: str = config.get("org_name", "")
        self._project: str = config.get("project_name", "")
        self._pat: str = config.get("pat", "")
        self._wiki_id: str = config.get("wiki_id", "")

    # ── Guards ────────────────────────────────────────────────────────────────

    def _is_configured(self) -> bool:
        if not self._enabled:
            return False
        missing = [k for k, v in {
            "org_name": self._org,
            "project_name": self._project,
            "pat": self._pat,
            "wiki_id": self._wiki_id,
        }.items() if not v]
        if missing:
            logger.warning("ADOWikiAdapter: missing config keys: %s", missing)
            return False
        return True

    def _headers(self) -> dict[str, str]:
        return {
            "Authorization": f"Basic {_b64_auth(self._pat)}",
            "Content-Type": "application/json",
        }

    # ── Wiki discovery ────────────────────────────────────────────────────────

    def _resolve_wiki_id(self, client: httpx.Client) -> Optional[str]:
        """
        If wiki_id is already a GUID or known slug, return it directly.
        Otherwise, list wikis and return the first project wiki found.
        """
        if self._wiki_id and self._wiki_id.lower() != "auto":
            return self._wiki_id

        url = f"https://dev.azure.com/{self._org}/{self._project}/_apis/wiki/wikis?api-version=7.1"
        try:
            resp = client.get(url, headers=self._headers())
            resp.raise_for_status()
            wikis = resp.json().get("value", [])
            if wikis:
                wiki_id = wikis[0]["id"]
                logger.info("ADOWikiAdapter: auto-resolved wiki id = %s", wiki_id)
                return wiki_id
            logger.warning("ADOWikiAdapter: no wikis found in project %s", self._project)
        except Exception as exc:
            logger.warning("ADOWikiAdapter: failed to list wikis: %s", exc)
        return None

    # ── Page creation ─────────────────────────────────────────────────────────

    def publish_investigation(self, result: InvestigationResult) -> Optional[str]:
        """
        Create (or update) a Wiki page for this investigation.
        Returns the page URL on success, None on failure / disabled.
        """
        if not self._is_configured():
            return None

        date_str = datetime.now(timezone.utc).strftime("%Y-%m-%d")
        svc = _safe_path_segment(result.request.service_name)
        env = _safe_path_segment(result.request.environment)
        page_name = f"{date_str}_{svc}_{env}"
        page_path = f"/{_WIKI_ROOT}/{page_name}"
        content = _build_wiki_content(result)

        try:
            with httpx.Client(timeout=30) as client:
                wiki_id = _resolve_wiki_id_with_client(self, client)
                if not wiki_id:
                    return None

                # Ensure root "Investigations" parent page exists
                self._ensure_parent_page(client, wiki_id)

                # PUT creates or updates the page
                url = (
                    f"https://dev.azure.com/{self._org}/{self._project}"
                    f"/_apis/wiki/wikis/{wiki_id}/pages"
                    f"?path={httpx.URL(path=page_path)}&api-version=7.1"
                )
                payload = {"content": content}
                resp = client.put(url, json=payload, headers=self._headers())

                if resp.status_code in (200, 201):
                    page_url = (
                        f"https://dev.azure.com/{self._org}/{self._project}"
                        f"/_wiki/wikis/{wiki_id}/pages?path={page_path}"
                    )
                    logger.info(
                        "ADOWikiAdapter: published page %s → %s", page_path, page_url
                    )
                    return page_url
                else:
                    logger.warning(
                        "ADOWikiAdapter: unexpected status %s: %s",
                        resp.status_code,
                        resp.text[:200],
                    )
                    return None

        except Exception as exc:  # noqa: BLE001
            logger.warning("ADOWikiAdapter: publish_investigation failed: %s", exc)
            return None

    def _ensure_parent_page(self, client: httpx.Client, wiki_id: str) -> None:
        """Create the 'Investigations' parent page if it doesn't exist yet."""
        parent_path = f"/{_WIKI_ROOT}"
        url = (
            f"https://dev.azure.com/{self._org}/{self._project}"
            f"/_apis/wiki/wikis/{wiki_id}/pages"
            f"?path={httpx.URL(path=parent_path)}&api-version=7.1"
        )
        # Check existence
        try:
            resp = client.get(url, headers=self._headers())
            if resp.status_code == 200:
                return  # already exists
        except Exception:
            pass

        # Create it
        try:
            payload = {"content": "# Corvin Investigations\n\nAll automated investigation reports live here.\n"}
            client.put(url, json=payload, headers=self._headers())
        except Exception as exc:
            logger.warning("ADOWikiAdapter: could not ensure parent page: %s", exc)


def _resolve_wiki_id_with_client(adapter: ADOWikiAdapter, client: httpx.Client) -> Optional[str]:
    """Module-level helper so tests can patch it easily."""
    return adapter._resolve_wiki_id(client)
