"""The files the DBA receives: headers without a timestamp, the confirmation guard, the runner, the manifest and how the files are written."""

from __future__ import annotations

import hashlib
import json
from datetime import UTC, datetime
from pathlib import Path

from sqlalchemy import Column, ForeignKey, MetaData, String, Table

from support import scripts_path  # noqa: F401  (puts backend/scripts on sys.path)

from demo_data_sql.demo_data_plan import DemoDataFileDeclaration, build_demo_data_plan  # noqa: E402
from demo_data_sql.script_writer import GenerationSettings, render_demo_data_scripts, write_scripts  # noqa: E402

SETTINGS = GenerationSettings(schema_name="keigan", reference_time=datetime(2026, 11, 20, 12, 0, tzinfo=UTC), random_seed=0)


def build_scripts(*, runtime_rows: int = 3) -> dict[str, str]:
    metadata = MetaData()
    Table("team", metadata, Column("team_id", String(36), primary_key=True), Column("team_name", String(50)))
    Table("member", metadata, Column("member_id", String(36), primary_key=True), Column("team_id", ForeignKey("team.team_id")), Column("member_name", String(50)))
    Table("history", metadata, Column("history_id", String(36), primary_key=True))
    Table("job_queue", metadata, Column("job_id", String(36), primary_key=True))
    Table("lonely", metadata, Column("lonely_id", String(36), primary_key=True))
    rows = {
        "lonely": [],
        "team": [{"team_id": "t1", "team_name": "請求チーム"}],
        "member": [{"member_id": "m1", "team_id": "t1", "member_name": "Aiko"}, {"member_id": "m2", "team_id": "t1", "member_name": "Rui"}],
        "history": [{"history_id": "h1"}],
        "job_queue": [{"job_id": f"j{number}"} for number in range(runtime_rows)],
    }
    declarations = (
        DemoDataFileDeclaration("01_people.sql", "Demo data 1: people", ("team", "member")),
        DemoDataFileDeclaration("02_history.sql", "Demo data 2: history (large)", ("history",), committed=False),
    )
    plan = build_demo_data_plan(metadata, {name: len(table_rows) for name, table_rows in rows.items()}, declarations, {"job_queue": "Queue rows would be run by the workers."})
    return render_demo_data_scripts(plan, rows, SETTINGS)


def test_a_step_file_starts_with_a_fixed_header_the_confirmation_guard_and_ends_with_go() -> None:
    text = build_scripts()["01_people.sql"]
    assert text.startswith(
        "-- Demo data 1: people\n"
        "-- Generated by backend/scripts/generate_demo_data_sql.py from the Keigan demo seed (reference time 2026-11-20 12:00 UTC, random seed 0). Do not edit by hand.\n"
        "-- DEMO DATA ONLY: never run this on a production database. Safe to run twice: rows whose key already exists are skipped.\n"
        ":on error exit\n"
        "SET NOCOUNT ON;\n"
        "GO\n\n"
        "IF N'$(ConfirmDemoData)' <> N'yes' THROW 50000, N'Demo data scripts are for non-production databases only. Run again with sqlcmd -v ConfirmDemoData=yes to confirm.', 1;\n"
        "GO\n\n"
    )
    assert text.endswith("\nGO\n")


def test_the_header_holds_no_generation_time_so_two_runs_on_different_days_give_identical_files() -> None:
    first, second = build_scripts(), build_scripts()
    assert first == second
    assert "Generated by backend/scripts/generate_demo_data_sql.py from" in first["01_people.sql"]
    assert " on 20" not in first["01_people.sql"]


def test_tables_are_written_parent_first_inside_a_step_file() -> None:
    text = build_scripts()["01_people.sql"]
    assert text.index("[keigan].[team]") < text.index("[keigan].[member]")


def test_the_removal_script_is_one_file_guarded_the_same_way_and_deletes_children_first() -> None:
    text = build_scripts()["99_remove_demo_data.sql"]
    assert ":on error exit" in text and "ConfirmDemoData" in text
    assert text.index("DELETE FROM [keigan].[history]") < text.index("DELETE FROM [keigan].[member]") < text.index("DELETE FROM [keigan].[team]")
    assert "job_queue" not in text
    assert text.count("DELETE FROM") == 3


def test_the_runner_lists_committed_step_files_in_order_and_points_to_the_on_demand_file_in_a_comment() -> None:
    text = build_scripts()["run_all_demo_data.sql"]
    assert ":r 01_people.sql" in text
    assert ":r 02_history.sql" not in text
    assert "-- 02_history.sql is generated on demand" in text
    assert "99_remove_demo_data.sql" not in text, "the runner must never remove data"


def test_the_gitignore_lists_exactly_the_on_demand_files() -> None:
    assert build_scripts()[".gitignore"] == "# Too large to commit; produced by backend/scripts/generate_demo_data_sql.py on demand.\n02_history.sql\n"


def test_the_manifest_records_row_counts_per_table_and_the_sha256_of_every_script() -> None:
    scripts = build_scripts()
    manifest = json.loads(scripts["MANIFEST.json"])
    assert manifest["generated_with"] == {"reference_time": "2026-11-20T12:00:00+00:00", "random_seed": 0, "schema_name": "keigan"}
    assert manifest["files"]["01_people.sql"]["rows"] == {"team": 1, "member": 2}
    assert manifest["files"]["01_people.sql"]["committed"] is True
    assert manifest["files"]["02_history.sql"] == {"committed": False, "rows": {"history": 1}, "sha256": hashlib.sha256(scripts["02_history.sql"].encode("utf-8")).hexdigest()}
    assert manifest["files"]["99_remove_demo_data.sql"]["rows"] == {"team": 1, "member": 2, "history": 1}
    for file_name, entry in manifest["files"].items():
        assert entry["sha256"] == hashlib.sha256(scripts[file_name].encode("utf-8")).hexdigest()


def test_the_manifest_lists_excluded_tables_with_their_reason_and_how_many_rows_the_seed_wrote() -> None:
    manifest = json.loads(build_scripts(runtime_rows=3)["MANIFEST.json"])
    assert manifest["excluded_tables"] == {"job_queue": {"reason": "Queue rows would be run by the workers.", "seeded_rows": 3}}


def test_files_are_written_as_utf_8_without_byte_order_mark_and_with_unix_line_endings(tmp_path: Path) -> None:
    write_scripts(tmp_path, build_scripts())
    raw = (tmp_path / "01_people.sql").read_bytes()
    assert not raw.startswith(b"\xef\xbb\xbf")
    assert b"\r" not in raw
    assert "請求チーム".encode() in raw


def test_writing_removes_sql_files_an_older_run_left_behind_but_keeps_other_files(tmp_path: Path) -> None:
    (tmp_path / "07_old_step.sql").write_text("-- Old\n-- Generated by backend/scripts/generate_demo_data_sql.py from the Keigan demo seed", encoding="utf-8")
    (tmp_path / "README.md").write_text("keep me", encoding="utf-8")
    write_scripts(tmp_path, build_scripts())
    assert not (tmp_path / "07_old_step.sql").exists()
    assert (tmp_path / "README.md").read_text(encoding="utf-8") == "keep me"


def test_writing_never_deletes_a_sql_file_this_generator_did_not_write(tmp_path: Path) -> None:
    """Someone may point the generator at database/azure_sql by mistake: the table scripts there must survive."""
    (tmp_path / "02_create_tables.sql").write_text("-- Generated by backend/scripts/generate_azure_sql_ddl.py", encoding="utf-8")
    write_scripts(tmp_path, build_scripts())
    assert (tmp_path / "02_create_tables.sql").exists()


def test_the_manifest_lists_the_tables_the_seed_left_empty_so_every_table_is_accounted_for() -> None:
    manifest = json.loads(build_scripts()["MANIFEST.json"])
    assert manifest["tables_without_seeded_rows"] == ["lonely"]
