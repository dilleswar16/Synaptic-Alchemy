"""Assembles the files the DBA receives (step files, removal script, runner, manifest, .gitignore) and writes them.

Nothing in a file depends on the day it was generated, so a regeneration on any machine and any day is byte for byte the same
(the drift test relies on it). ``MANIFEST.json`` records row counts and a SHA-256 per file, which also covers the on-demand file
that is too large to commit.
"""

from __future__ import annotations

import hashlib
import json
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Any

from demo_data_sql.demo_data_plan import DemoDataPlan
from demo_data_sql.statement_builders import build_insert_blocks, build_removal_blocks

REMOVAL_FILE_NAME = "99_remove_demo_data.sql"
RUNNER_FILE_NAME = "run_all_demo_data.sql"
MANIFEST_FILE_NAME = "MANIFEST.json"
GITIGNORE_FILE_NAME = ".gitignore"
CONFIRMATION_VARIABLE = "ConfirmDemoData"
GENERATOR_MARKER = "backend/scripts/generate_demo_data_sql.py"
BATCH_SEPARATOR = "\nGO\n\n"


@dataclass(frozen=True)
class GenerationSettings:
    schema_name: str
    reference_time: datetime  # the fixed clock of the seed run; stated in the header so the data's "now" is known
    random_seed: int


def _header(title: str, settings: GenerationSettings) -> str:
    reference = settings.reference_time.strftime("%Y-%m-%d %H:%M")
    return (
        f"-- {title}\n"
        f"-- Generated by {GENERATOR_MARKER} from the Keigan demo seed (reference time {reference} UTC, random seed {settings.random_seed}). Do not edit by hand.\n"
        "-- DEMO DATA ONLY: never run this on a production database. Safe to run twice: rows whose key already exists are skipped.\n"
        ":on error exit\n"
        "SET NOCOUNT ON;\n"
        "GO\n\n"
        f"IF N'$({CONFIRMATION_VARIABLE})' <> N'yes' THROW 50000, N'Demo data scripts are for non-production databases only. Run again with sqlcmd -v {CONFIRMATION_VARIABLE}=yes to confirm.', 1;\n"
        "GO\n\n"
    )


def _script(title: str, blocks: Sequence[str], settings: GenerationSettings) -> str:
    return _header(title, settings) + BATCH_SEPARATOR.join(blocks) + "\nGO\n"


def _runner(plan: DemoDataPlan, settings: GenerationSettings) -> str:
    lines = [
        "-- Runs the committed demo data steps in order. DEMO DATA ONLY: never run this on a production database.",
        f"--   sqlcmd -S <server>.database.windows.net -d <database> --authentication-method ActiveDirectoryDefault -b -f 65001 -v {CONFIRMATION_VARIABLE}=yes -i {RUNNER_FILE_NAME}",
        "-- Run it from this folder (sqlcmd resolves :r paths from the current directory). Never include it from ../run_all.sql.",
        ":on error exit",
    ]
    for planned_file in plan.files:
        declaration = planned_file.declaration
        if not planned_file.tables:
            continue
        lines.append(f":r {declaration.file_name}" if declaration.committed else f"-- {declaration.file_name} is generated on demand and optional: see README.md")
    return "\n".join(lines) + "\n"


def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _manifest(plan: DemoDataPlan, rows_by_table: Mapping[str, Sequence[Any]], scripts: Mapping[str, str], settings: GenerationSettings) -> str:
    files: dict[str, Any] = {}
    for planned_file in plan.files:
        if planned_file.tables:
            name = planned_file.declaration.file_name
            files[name] = {"committed": planned_file.declaration.committed, "rows": {table.name: len(rows_by_table[table.name]) for table in planned_file.tables}, "sha256": _sha256(scripts[name])}
    all_rows = {table.name: len(rows_by_table[table.name]) for table in plan.tables_in_insert_order}
    files[REMOVAL_FILE_NAME] = {"committed": True, "rows": all_rows, "sha256": _sha256(scripts[REMOVAL_FILE_NAME])}
    files[RUNNER_FILE_NAME] = {"committed": True, "rows": {}, "sha256": _sha256(scripts[RUNNER_FILE_NAME])}
    manifest = {
        "generated_with": {"reference_time": settings.reference_time.isoformat(), "random_seed": settings.random_seed, "schema_name": settings.schema_name},
        "files": files,
        "tables_without_seeded_rows": sorted(name for name, rows in rows_by_table.items() if not rows and name not in plan.excluded_table_reasons),
        "excluded_tables": {name: {"reason": reason, "seeded_rows": len(rows_by_table.get(name, ()))} for name, reason in plan.excluded_table_reasons.items()},
    }
    return json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"


def render_demo_data_scripts(plan: DemoDataPlan, rows_by_table: Mapping[str, Sequence[Mapping[str, Any]]], settings: GenerationSettings) -> dict[str, str]:
    """File name to file text for every generated file, in the order they should be written."""
    scripts: dict[str, str] = {}
    for planned_file in plan.files:
        if not planned_file.tables:
            continue
        blocks = [block for table in planned_file.tables for block in build_insert_blocks(table, rows_by_table[table.name], settings.schema_name)]
        scripts[planned_file.declaration.file_name] = _script(planned_file.declaration.title, blocks, settings)
    removal_blocks = build_removal_blocks(plan.tables_in_insert_order, rows_by_table, settings.schema_name)
    scripts[REMOVAL_FILE_NAME] = _script("Remove demo data: deletes ONLY the rows the demo scripts insert, by key, children before parents", removal_blocks, settings)
    scripts[RUNNER_FILE_NAME] = _runner(plan, settings)
    scripts[MANIFEST_FILE_NAME] = _manifest(plan, rows_by_table, scripts, settings)
    on_demand_files = [planned_file.declaration.file_name for planned_file in plan.files if planned_file.tables and not planned_file.declaration.committed]
    scripts[GITIGNORE_FILE_NAME] = "# Too large to commit; produced by backend/scripts/generate_demo_data_sql.py on demand.\n" + "".join(f"{name}\n" for name in on_demand_files)
    return scripts


def _was_written_by_this_generator(script_file: Path) -> bool:
    """Only files that carry our marker may be deleted, so pointing the generator at the wrong folder cannot remove the table scripts."""
    with script_file.open(encoding="utf-8") as opened:
        return GENERATOR_MARKER in "".join(opened.readline() for _ in range(3))


def write_scripts(output_directory: Path, scripts: Mapping[str, str]) -> None:
    """Write UTF-8 without a byte order mark and with Unix line endings; drop .sql files an older run left behind."""
    output_directory.mkdir(parents=True, exist_ok=True)
    for stale_file in output_directory.glob("*.sql"):
        if stale_file.name not in scripts and _was_written_by_this_generator(stale_file):
            stale_file.unlink()
    for file_name, text in scripts.items():
        (output_directory / file_name).write_text(text, encoding="utf-8", newline="\n")
