"""Generates one SQL Server delta script per Alembic revision after the baseline, for DBAs who apply schema changes by hand.

Usage (from backend/):  .\\.venv\\Scripts\\python.exe scripts\\generate_azure_sql_migration_scripts.py [output folder] [schema]
Default output: ../database/azure_sql/migrations, default schema: keigan.

The SQL comes from Alembic offline mode (``alembic upgrade <old>:<new> --sql``) so it is exactly what the Helm pre-upgrade job would run
and cannot drift from the migrations. Never edit the output by hand. Each script also moves ``alembic_version``, so a database that
ran it is recognised by ``alembic upgrade head`` afterwards. Run the scripts in revision order, each one once.
"""

from __future__ import annotations

import io
import os
import sys
from pathlib import Path

OUTPUT_DIRECTORY = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[2] / "database" / "azure_sql" / "migrations"
SCHEMA_NAME = sys.argv[2] if len(sys.argv) > 2 else "keigan"

# Configure for SQL Server before any Keigan module is imported (migrations read the schema at import time).
os.environ["DATABASE_URL"] = "mssql+aioodbc://@server.database.windows.net:1433/keigan?driver=ODBC+Driver+18+for+SQL+Server"
os.environ["DATABASE_SCHEMA"] = SCHEMA_NAME
os.environ.setdefault("LLM_PROVIDER", "mock")
os.environ.setdefault("ENVIRONMENT", "local")
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from alembic import command  # noqa: E402
from alembic.config import Config  # noqa: E402
from alembic.script import ScriptDirectory  # noqa: E402

BACKEND_DIRECTORY = Path(__file__).resolve().parents[1]
FILE_HEADER = (
    "-- Generated by backend/scripts/generate_azure_sql_migration_scripts.py from Alembic offline mode ({old}:{new}).\n"
    "-- Do not edit by hand. Run once, on a database whose keigan.alembic_version is {old}; it moves the version to {new}.\n"
    "-- Databases created from 01-06 after this revision already include these changes: do not run it there.\n"
)


def main() -> None:
    alembic_configuration = Config(str(BACKEND_DIRECTORY / "alembic.ini"))
    alembic_configuration.set_main_option("script_location", str(BACKEND_DIRECTORY / "migrations"))
    script_directory = ScriptDirectory.from_config(alembic_configuration)
    OUTPUT_DIRECTORY.mkdir(parents=True, exist_ok=True)
    revisions_oldest_first = list(reversed(list(script_directory.walk_revisions())))
    for revision in revisions_oldest_first[1:]:  # the first revision is the baseline created by scripts 01-06
        previous_revision = revision.down_revision
        assert isinstance(previous_revision, str), "linear history expected"
        output_buffer = io.StringIO()
        alembic_configuration.output_buffer = output_buffer
        command.upgrade(alembic_configuration, f"{previous_revision}:{revision.revision}", sql=True)
        slug = Path(revision.path).stem.split(f"_{revision.revision}_", 1)[1]  # file name: <date>_<revision>_<slug>
        target_file = OUTPUT_DIRECTORY / f"{revision.revision}_{slug}.sql"
        target_file.write_text(FILE_HEADER.format(old=previous_revision, new=revision.revision) + output_buffer.getvalue(), encoding="utf-8", newline="\n")
        print(f"wrote {target_file.name}")


if __name__ == "__main__":
    main()
