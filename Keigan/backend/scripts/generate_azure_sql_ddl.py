"""Generates the Azure SQL (SQL Server) DDL scripts from Keigan's entities — the single source of truth.

Usage (from backend/):  .\\.venv\\Scripts\\python.exe scripts\\generate_azure_sql_ddl.py [output folder] [schema]
Default output: ../database/azure_sql, default schema: keigan. Re-run after any entity change and commit the result.
Every script is idempotent (safe to run twice) and separated into batches with GO for sqlcmd / SSMS / Azure Data Studio.
"""

from __future__ import annotations

import os
import sys
from datetime import UTC, datetime
from pathlib import Path

OUTPUT_DIRECTORY = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[2] / "database" / "azure_sql"
SCHEMA_NAME = sys.argv[2] if len(sys.argv) > 2 else "keigan"

# Configure the metadata for SQL Server before any Keigan module is imported (the schema is read at import time).
os.environ["DATABASE_URL"] = "mssql+aioodbc://@server.database.windows.net:1433/keigan?driver=ODBC+Driver+18+for+SQL+Server"
os.environ["DATABASE_SCHEMA"] = SCHEMA_NAME
os.environ.setdefault("LLM_PROVIDER", "mock")
os.environ.setdefault("ENVIRONMENT", "local")
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from alembic.config import Config  # noqa: E402
from alembic.script import ScriptDirectory  # noqa: E402
from sqlalchemy.dialects import mssql  # noqa: E402
from sqlalchemy.schema import AddConstraint, CreateIndex, CreateTable  # noqa: E402

from keigan.config.settings import get_settings  # noqa: E402
from keigan.entities import all_entities  # noqa: E402, F401
from keigan.entities.base_entity import EntityBase  # noqa: E402

SQL_SERVER_DIALECT = mssql.dialect()
GENERATED_NOTICE = (
    f"-- Generated by backend/scripts/generate_azure_sql_ddl.py on {datetime.now(UTC):%Y-%m-%d %H:%M} UTC from the Keigan entities.\n"
    "-- Do not edit by hand: change the entity, regenerate, and review the diff.\n"
)


def compile_statement(statement: object) -> str:
    return str(statement.compile(dialect=SQL_SERVER_DIALECT)).strip()  # type: ignore[attr-defined]


def qualified_name(table_name: str) -> str:
    return f"[{SCHEMA_NAME}].[{table_name}]"


def write_script(file_name: str, title: str, batches: list[str]) -> None:
    script_text = f"-- {title}\n{GENERATED_NOTICE}SET NOCOUNT ON;\nGO\n\n" + "\nGO\n\n".join(batches) + "\nGO\n"
    (OUTPUT_DIRECTORY / file_name).write_text(script_text, encoding="utf-8", newline="\n")
    print(f"wrote {file_name} ({len(batches)} batches)")


def main() -> None:
    if get_settings().database_schema_or_none != SCHEMA_NAME:
        raise SystemExit("The entity metadata did not pick up the schema; run this script directly, not via an import.")
    OUTPUT_DIRECTORY.mkdir(parents=True, exist_ok=True)
    tables = EntityBase.metadata.sorted_tables

    write_script("01_create_schema.sql", "Step 1 of 6 — schema", [
        f"IF NOT EXISTS (SELECT 1 FROM sys.schemas WHERE name = N'{SCHEMA_NAME}')\n    EXEC (N'CREATE SCHEMA [{SCHEMA_NAME}] AUTHORIZATION [dbo]');",
    ])

    write_script("02_create_tables.sql", f"Step 2 of 6 — {len(tables)} tables (primary keys, unique constraints; foreign keys follow in step 3)", [
        f"IF OBJECT_ID(N'{SCHEMA_NAME}.{table.name}', N'U') IS NULL\nBEGIN\n{compile_statement(CreateTable(table, include_foreign_key_constraints=[]))};\nEND"
        for table in tables
    ])

    foreign_key_batches = [
        f"IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'{constraint.name}' AND parent_object_id = OBJECT_ID(N'{SCHEMA_NAME}.{table.name}'))\n"
        f"    {compile_statement(AddConstraint(constraint))};"
        for table in tables
        for constraint in sorted(table.foreign_key_constraints, key=lambda foreign_key: str(foreign_key.name))
    ]
    write_script("03_create_foreign_keys.sql", f"Step 3 of 6 — {len(foreign_key_batches)} foreign keys (one cascade path per table, as SQL Server requires)", foreign_key_batches)

    index_batches = [
        f"IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'{index.name}' AND object_id = OBJECT_ID(N'{SCHEMA_NAME}.{table.name}'))\n"
        f"    {compile_statement(CreateIndex(index))};"
        for table in tables
        for index in sorted(table.indexes, key=lambda table_index: str(table_index.name))
    ]
    write_script("04_create_indexes.sql", f"Step 4 of 6 — {len(index_batches)} indexes", index_batches)

    alembic_configuration = Config(str(Path(__file__).resolve().parents[1] / "alembic.ini"))
    alembic_configuration.set_main_option("script_location", str(Path(__file__).resolve().parents[1] / "migrations"))
    head_revision = ScriptDirectory.from_config(alembic_configuration).get_current_head()
    write_script("05_reference_data.sql", "Step 5 of 6 — reference data (migration baseline and schema marker)", [
        f"IF OBJECT_ID(N'{SCHEMA_NAME}.alembic_version', N'U') IS NULL\n"
        f"    CREATE TABLE {qualified_name('alembic_version')} (version_num NVARCHAR(32) NOT NULL CONSTRAINT pk_alembic_version PRIMARY KEY);",
        f"-- Marks this database as created at migration {head_revision}; later releases apply only newer migrations.\n"
        f"IF NOT EXISTS (SELECT 1 FROM {qualified_name('alembic_version')})\n"
        f"    INSERT INTO {qualified_name('alembic_version')} (version_num) VALUES (N'{head_revision}');",
        f"IF NOT EXISTS (SELECT 1 FROM {qualified_name('platform_setting')} WHERE setting_key = N'database_schema')\n"
        f"    INSERT INTO {qualified_name('platform_setting')} (setting_key, setting_value_json, setting_description, updated_at, updated_by_user_principal_name)\n"
        f"    VALUES (N'database_schema', N'{{\"schema\": \"{SCHEMA_NAME}\", \"baselineRevision\": \"{head_revision}\", \"createdBy\": \"azure_sql_ddl_scripts\"}}',\n"
        f"            N'Created by the Azure SQL DDL scripts. Applications, users and all other data are created through Keigan.', SYSUTCDATETIME(), N'system:ddl');",
    ])

    write_script("06_grant_keigan_identity.sql", "Step 6 of 6 — database user for Keigan's managed identity (run as the server's Entra admin)", [
        "-- Needs the SQLCMD variable KeiganIdentityName = display name of Keigan's user-assigned managed identity (e.g. id-keigan-prod).\n"
        "--   sqlcmd: pass -v KeiganIdentityName=id-keigan-prod (sqlcmd stops with 'scripting variable not defined' if it is missing).\n"
        "--   SSMS / Azure Data Studio: turn on Query > SQLCMD Mode and uncomment the next line.\n"
        "-- :setvar KeiganIdentityName id-keigan-prod\n"
        "PRINT N'Creating the database user for $(KeiganIdentityName)';",
        f"IF NOT EXISTS (SELECT 1 FROM sys.database_principals WHERE name = N'$(KeiganIdentityName)')\n"
        f"    CREATE USER [$(KeiganIdentityName)] FROM EXTERNAL PROVIDER WITH DEFAULT_SCHEMA = [{SCHEMA_NAME}];",
        f"-- Day-to-day access: read and write data in Keigan's schema only.\nGRANT SELECT, INSERT, UPDATE, DELETE ON SCHEMA::[{SCHEMA_NAME}] TO [$(KeiganIdentityName)];",
        "-- Optional: lets the Helm migration job apply future schema changes itself (python -m alembic upgrade head).\n"
        "-- Leave commented out if your DBAs apply schema changes with these scripts instead.\n"
        f"-- GRANT ALTER ON SCHEMA::[{SCHEMA_NAME}] TO [$(KeiganIdentityName)];\n"
        "-- GRANT CREATE TABLE TO [$(KeiganIdentityName)];\n"
        "-- GRANT REFERENCES TO [$(KeiganIdentityName)];\n"
        "SELECT N'Keigan identity $(KeiganIdentityName) can now use the database.' AS result;",
    ])

    run_all_lines = [
        "-- Runs every step in order. Run from this folder (sqlcmd resolves :r paths from the current directory):",
        "--   sqlcmd -S <server>.database.windows.net -d <database> --authentication-method ActiveDirectoryDefault -b -i run_all.sql -v KeiganIdentityName=id-keigan-prod",
        "-- -b stops at the first error. Every step is idempotent, so a fixed re-run is safe.",
        ":on error exit",
        *[f":r {script_name}" for script_name in ("01_create_schema.sql", "02_create_tables.sql", "03_create_foreign_keys.sql", "04_create_indexes.sql", "05_reference_data.sql", "06_grant_keigan_identity.sql")],
    ]
    (OUTPUT_DIRECTORY / "run_all.sql").write_text("\n".join(run_all_lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote run_all.sql · tables={len(tables)} foreign_keys={len(foreign_key_batches)} indexes={len(index_batches)} baseline={head_revision}")


if __name__ == "__main__":
    main()
