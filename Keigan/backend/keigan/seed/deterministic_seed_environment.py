"""A repeatable run of the demo seed: fixed clock, sequential identifiers and a fixed random sequence.

Why: the demo data is also published as reviewed SQL for the DBA (``database/azure_sql/demo_data``). That SQL is generated by running
this seed, and a test compares a fresh generation with the committed manifest, so two runs must produce identical rows.

Trade-off, stated plainly: the seed and the services it calls read the clock (``datetime.now``), ``uuid.uuid4``, ``random`` and
``secrets`` directly. Editing every service to take an injected clock would touch production code for a tool that only needs it once,
so instead this module substitutes those sources GLOBALLY for the duration of one ``with`` block:

- ``datetime`` is replaced in every already imported ``keigan`` module that did ``from datetime import datetime``;
- ``uuid.uuid4``, ``secrets.token_hex``, ``secrets.token_urlsafe`` and ``secrets.token_bytes`` are replaced on their modules;
- ``evidence_service.MAXIMUM_CONCURRENT_QUERIES`` is set to 1: concurrent evidence queries share one masking counter, so with several in
  flight the per-evidence ``masked_value_count`` depends on how the event loop interleaves them (a defect to fix in that service; until then
  the seed runs them one at a time to stay reproducible);
- the global ``random`` generator is re-seeded (its previous state is saved).

Everything is put back when the block exits, also when it raises. Use it only in a script or test that owns the process (the demo SQL
generator, tests): anything else running at the same time, in another thread for example, would see the fixed values. Not covered:
``os.urandom``, ``random.SystemRandom``, ``time.time`` and ``time.monotonic`` (a frozen monotonic clock would stop every cache that expires by age,
which changed the seeded data) and modules that ``import datetime`` and call ``datetime.datetime.now``.
The naive ``datetime.now()`` returns UTC (not machine local time) so the result does not depend on the machine's time zone.
"""

from __future__ import annotations

import base64
import importlib
import logging
import pkgutil
import random
import secrets
import sys
import uuid
from collections.abc import Callable, Iterator
from contextlib import contextmanager
from datetime import UTC, datetime, tzinfo

import keigan

logger = logging.getLogger(__name__)
_RealDatetime = datetime
DEFAULT_SECRET_BYTE_COUNT = secrets.DEFAULT_ENTROPY


class _DatetimeMeta(type(_RealDatetime)):  # type: ignore[misc]
    def __instancecheck__(cls, instance: object) -> bool:
        """Datetimes made by libraries (the database driver, for example) must still count as ``datetime`` in Keigan code."""
        return isinstance(instance, _RealDatetime)


def _build_fixed_clock_datetime(reference_time: datetime) -> type[datetime]:
    """A ``datetime`` replacement whose ``now()`` always returns ``reference_time``."""
    fixed_now = reference_time.astimezone(UTC)

    class FixedClockDatetime(_RealDatetime, metaclass=_DatetimeMeta):  # type: ignore[misc,valid-type]
        @classmethod
        def now(cls, tz: tzinfo | None = None) -> datetime:  # type: ignore[override]
            return fixed_now.astimezone(tz) if tz is not None else fixed_now.replace(tzinfo=None)

        @classmethod
        def utcnow(cls) -> datetime:  # type: ignore[override]
            return fixed_now.replace(tzinfo=None)

    return FixedClockDatetime


def _sequential_identifier_source() -> Callable[[], uuid.UUID]:
    """``uuid4`` replacement: valid version 4 UUIDs counting up (``...-000000000001``), so rows read in creation order."""
    counter = 0

    def next_identifier() -> uuid.UUID:
        nonlocal counter
        counter += 1
        return uuid.UUID(int=counter, version=4)

    return next_identifier


def _import_every_keigan_module() -> None:
    """Import all modules first: a module imported later would bind the real clock and escape the substitution."""
    for module_information in pkgutil.walk_packages(keigan.__path__, "keigan."):
        try:
            importlib.import_module(module_information.name)
        except ImportError:
            logger.warning("Module %s needs an optional package that is not installed; the seed cannot reach it either", module_information.name)


@contextmanager
def deterministic_seed_environment(reference_time: datetime, random_seed: int = 0) -> Iterator[None]:
    """Run the seed as if it were ``reference_time`` with reproducible identifiers, random numbers and generated secrets."""
    _import_every_keigan_module()
    fixed_clock_datetime = _build_fixed_clock_datetime(reference_time)
    patched_modules = [
        module for name, module in list(sys.modules.items())
        if (name == "keigan" or name.startswith("keigan.")) and getattr(module, "datetime", None) is _RealDatetime
    ]
    from keigan.services import evidence_service

    real_concurrent_query_limit = evidence_service.MAXIMUM_CONCURRENT_QUERIES
    real_sources = (uuid.uuid4, secrets.token_bytes, secrets.token_hex, secrets.token_urlsafe)
    saved_random_state = random.getstate()
    secret_source = random.Random(random_seed)

    def token_bytes(byte_count: int | None = None) -> bytes:
        return secret_source.randbytes(byte_count or DEFAULT_SECRET_BYTE_COUNT)

    def token_hex(byte_count: int | None = None) -> str:
        return token_bytes(byte_count).hex()

    def token_urlsafe(byte_count: int | None = None) -> str:
        return base64.urlsafe_b64encode(token_bytes(byte_count)).rstrip(b"=").decode("ascii")

    for module in patched_modules:
        module.datetime = fixed_clock_datetime  # type: ignore[attr-defined]
    evidence_service.MAXIMUM_CONCURRENT_QUERIES = 1
    uuid.uuid4 = _sequential_identifier_source()  # type: ignore[assignment]
    secrets.token_bytes, secrets.token_hex, secrets.token_urlsafe = token_bytes, token_hex, token_urlsafe
    random.seed(random_seed)
    try:
        yield
    finally:
        for module in patched_modules:
            module.datetime = _RealDatetime  # type: ignore[attr-defined]
        evidence_service.MAXIMUM_CONCURRENT_QUERIES = real_concurrent_query_limit
        uuid.uuid4, secrets.token_bytes, secrets.token_hex, secrets.token_urlsafe = real_sources
        random.setstate(saved_random_state)
