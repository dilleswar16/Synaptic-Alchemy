import { useState } from 'react'
import { useQuery } from '@tanstack/react-query'
import { fetchAllCommsDrafts } from '../../api/client'
import { InfoTooltip } from '../Section'

interface Props {
  requestId: string
}

const AUDIENCE_META: Record<string, { icon: string; label: string; color: string }> = {
  executive: { icon: '👔', label: 'Executive', color: 'var(--c-amber)' },
  internal: { icon: '🛠', label: 'Engineering', color: 'var(--c-signal)' },
  public: { icon: '🌐', label: 'Status Page', color: 'var(--c-info)' },
}

export function CommsDraftSection({ requestId }: Props) {
  const [expanded, setExpanded] = useState(false)
  const [activeTab, setActiveTab] = useState<string>('internal')
  const [copied, setCopied] = useState<string | null>(null)

  const { data, isLoading, error, refetch } = useQuery({
    queryKey: ['comms-drafts', requestId],
    queryFn: () => fetchAllCommsDrafts(requestId),
    enabled: expanded,
    staleTime: 300_000,
    retry: false,
  })

  const handleCopy = (text: string, audience: string) => {
    navigator.clipboard.writeText(text)
    setCopied(audience)
    setTimeout(() => setCopied(null), 2000)
  }

  return (
    <section style={{ marginTop: 24 }}>
      <div className="panel" style={{ overflow: 'hidden' }}>
        <div style={{
          padding: '12px 20px', borderBottom: '1px solid var(--c-border)',
          background: 'var(--c-surface-2)', display: 'flex', alignItems: 'center', justifyContent: 'space-between',
        }}>
          <span style={{ display: 'flex', alignItems: 'center', gap: 7, fontWeight: 600, fontSize: '0.8125rem', letterSpacing: '0.02em', color: 'var(--c-text-dim)' }}>
            Incident Communications
            <InfoTooltip text="Audience-specific incident communications generated by Corvin: an executive summary for leadership, an engineering technical brief, and a customer-facing status update. All drafts require review before use." />
          </span>
          <span style={{ fontFamily: 'var(--font-mono)', fontSize: '0.6rem', padding: '2px 7px', borderRadius: 4, background: 'var(--c-signal-glow)', color: 'var(--c-signal)', fontWeight: 700 }}>
            AI
          </span>
        </div>
        <div style={{ padding: '16px 20px' }}>
      {!expanded && (
        <button
          onClick={() => setExpanded(true)}
          style={{
            background: 'var(--c-signal-glow)', border: '1px solid var(--c-signal-dim)',
            color: 'var(--c-signal)', padding: '8px 16px', borderRadius: 6,
            cursor: 'pointer', fontFamily: 'var(--font-mono)', fontSize: '0.75rem',
            fontWeight: 600,
          }}
        >
          📝 Generate Comms Drafts
        </button>
      )}

      {isLoading && (
        <div style={{ display: 'flex', alignItems: 'center', gap: 8, padding: '16px 0' }}>
          <span style={{
            width: 10, height: 10, borderRadius: '50%',
            border: '1.5px solid var(--c-signal)', borderTopColor: 'transparent',
            display: 'inline-block', animation: 'skeleton-sweep 0.7s linear infinite',
          }} />
          <span style={{ fontFamily: 'var(--font-mono)', fontSize: '0.72rem', color: 'var(--c-signal)' }}>
            Drafting communications for all audiences…
          </span>
        </div>
      )}

      {error && (
        <div style={{ color: 'var(--c-red)', fontFamily: 'var(--font-mono)', fontSize: '0.75rem' }}>
          Failed to generate drafts.{' '}
          <button onClick={() => refetch()} style={{ color: 'var(--c-signal)', background: 'none', border: 'none', cursor: 'pointer', textDecoration: 'underline' }}>
            Retry
          </button>
        </div>
      )}

      {data && data.length > 0 && (
        <div style={{ display: 'flex', flexDirection: 'column', gap: 12 }}>
          {/* Audience tabs */}
          <div style={{ display: 'flex', gap: 0, borderBottom: '1px solid var(--c-border)' }}>
            {data.map(draft => {
              const meta = AUDIENCE_META[draft.audience] || AUDIENCE_META.internal
              return (
                <button
                  key={draft.audience}
                  onClick={() => setActiveTab(draft.audience)}
                  style={{
                    padding: '8px 14px', background: 'none', border: 'none',
                    borderBottom: `2px solid ${activeTab === draft.audience ? meta.color : 'transparent'}`,
                    marginBottom: -1, cursor: 'pointer',
                    color: activeTab === draft.audience ? 'var(--c-text)' : 'var(--c-text-muted)',
                    fontFamily: 'var(--font-mono)', fontSize: '0.72rem', fontWeight: 600,
                    display: 'flex', alignItems: 'center', gap: 5,
                  }}
                >
                  {meta.icon} {meta.label}
                </button>
              )
            })}
          </div>

          {/* Active draft */}
          {data.filter(d => d.audience === activeTab).map(draft => (
            <div key={draft.audience} style={{ position: 'relative' }}>
              <div style={{
                padding: '14px 16px', borderRadius: 8,
                background: 'var(--c-surface-2)', border: '1px solid var(--c-border)',
                fontFamily: 'var(--font-body)', fontSize: '0.82rem',
                color: 'var(--c-text-dim)', lineHeight: 1.7,
                whiteSpace: 'pre-wrap',
              }}>
                {draft.draft}
              </div>
              <button
                onClick={() => handleCopy(draft.draft, draft.audience)}
                style={{
                  position: 'absolute', top: 8, right: 8,
                  background: copied === draft.audience ? 'var(--c-success-bg)' : 'var(--c-surface)',
                  border: `1px solid ${copied === draft.audience ? 'var(--c-success-border)' : 'var(--c-border)'}`,
                  color: copied === draft.audience ? 'var(--c-green)' : 'var(--c-text-muted)',
                  padding: '4px 10px', borderRadius: 4, cursor: 'pointer',
                  fontFamily: 'var(--font-mono)', fontSize: '0.65rem', fontWeight: 600,
                }}
              >
                {copied === draft.audience ? '✓ Copied' : '📋 Copy'}
              </button>
              {draft.fallback && (
                <span style={{
                  display: 'inline-block', marginTop: 6,
                  fontFamily: 'var(--font-mono)', fontSize: '0.6rem',
                  color: 'var(--c-amber)', letterSpacing: '0.04em',
                }}>
                  ⚠ Fallback template (LLM unavailable)
                </span>
              )}
            </div>
          ))}
        </div>
      )}
        </div>
      </div>
    </section>
  )
}
